// Writes matlab/bs_lists.m from www/engine.js so the MATLAB feature extractor uses exactly the app's lists and weights.
// Run after changing engine.js:  node scripts/gen-matlab-lists.mjs
import fs from 'node:fs';
import * as E from '../www/engine.js';
const cell = (a) => '{' + a.map((s) => `'${String(s).replace(/'/g, "''")}'`).join(', ') + '}';
const brands = Object.entries(E.BRANDS).map(([b, d]) => `  '${b}', ${cell(d)}`).join('; ...\n');
const w = E.DEFAULT_WEIGHTS.url;
const out = `function L = bs_lists()
%BS_LISTS Reference lists and default weights shared with the BlackSwan app.
%   Generated by scripts/gen-matlab-lists.mjs from www/engine.js. Do not edit by hand.
L.features = ${cell(E.URL_FEATURES)};
L.brands = { ...
${brands} ...
};
L.shorteners = ${cell(E.SHORTENERS)};
L.freeHosts = ${cell(E.FREE_HOSTS)};
L.abusedTlds = ${cell(E.ABUSED_TLDS)};
L.redirectKeys = ${cell(E.REDIRECT_KEYS)};
L.loginWords = ${cell(E.LOGIN_WORDS)};
L.defaultBias = ${w.bias};
L.defaultW = [${E.URL_FEATURES.map((k) => w.w[k]).join(' ')}];
end
`;
fs.writeFileSync('matlab/bs_lists.m', out);
console.log('matlab/bs_lists.m written');
